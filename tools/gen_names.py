import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
pairs = re.findall(r'\{0x([0-9A-Fa-f]+), "([^"]*)"\}', src)
assert len(pairs) == 611, len(pairs)
ids = [int(a, 16) for a, _ in pairs]
assert ids == sorted(ids) and len(set(ids)) == len(ids)
for _, n in pairs:
    assert re.fullmatch(r'[A-Za-z0-9_./-]+', n) and '..' not in n and not n.startswith('/'), n
out = []
out.append('// SPDX-License-Identifier: GPL-3.0-or-later\n// Mr. Bin engine: Java translation of parts of shadPS4 (Copyright 2024 shadPS4 Emulator Project,\n// GPL-2.0-or-later) and LibOrbisPkg (Maxton, LGPL-3.0). See the README, "License and credits".\npackage io.github.codewizardqa.mrbin.engine.orbis;\n')
out.append('/**\n * PKG entry id → file name. GENERATED by gen_names.py from shadPS4 v0.7.0\n * src/core/file_format/pkg_type.cpp (GPL-2.0-or-later), 611 entries. Do not edit by hand.\n */')
out.append('final class PkgEntryNames {\n    private PkgEntryNames() {}\n')
out.append('    private static final int[] IDS = {')
for i in range(0, len(ids), 10):
    out.append('            ' + ', '.join('0x%04X' % x for x in ids[i:i+10]) + ',')
out.append('    };\n')
out.append('    private static final String[] NAMES = {')
for _, n in pairs:
    out.append('            "%s",' % n)
out.append('    };\n')
out.append('''    /** The shadPS4 name of an entry, or null when shadPS4 has none. */
    static String of(int id) {
        int i = java.util.Arrays.binarySearch(IDS, id);
        return i >= 0 ? NAMES[i] : null;
    }

    static int count() {
        return IDS.length;
    }
}''')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
